"""
Ejemplo: Contar apariciones de un carácter

Descripción detallada:
Este ejemplo muestra cómo contar cuántas veces aparece una letra en una cadena usando el método count.
"""

if __name__ == "__main__":
    frase = "banana"
    cantidad = frase.count("a")
    print(f"La letra 'a' aparece {cantidad} veces.")

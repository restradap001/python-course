"""
Ejemplo: Concatenación de cadenas

Descripción detallada:
Este ejemplo muestra cómo concatenar (unir) dos cadenas de texto usando el operador + en Python.
"""

if __name__ == "__main__":
    primera = "Good"   # Primera parte
    segunda = "Morning"  # Segunda parte
    resultado = primera + " " + segunda  # Concatenación
    print(resultado)

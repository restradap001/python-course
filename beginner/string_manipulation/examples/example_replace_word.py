"""
Ejemplo: Reemplazo de palabras en una cadena

Descripción detallada:
Este ejemplo muestra cómo reemplazar una palabra por otra en una cadena de texto usando el método replace.
"""

if __name__ == "__main__":
    frase = "Me gusta el café."
    nueva_frase = frase.replace("café", "té")
    print(nueva_frase)

"""
Ejemplo: Eliminar espacios al inicio y final

Descripción detallada:
Este ejemplo muestra cómo eliminar los espacios en blanco al inicio y al final de una cadena usando strip.
"""

if __name__ == "__main__":
    texto = "   Hola mundo   "
    texto_limpio = texto.strip()
    print(f"'{texto_limpio}'")

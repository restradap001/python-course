"""
Ejemplo: Formateo de cadenas

Descripción detallada:
Este ejemplo muestra cómo usar f-strings para formatear cadenas de texto en Python, insertando variables dentro de una cadena.
"""

if __name__ == "__main__":
    nombre = "Bob"  # Nombre
    edad = 22       # Edad
    # Mostramos la cadena formateada
    print(f"Me llamo {nombre} y tengo {edad} años.")

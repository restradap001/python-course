"""
Ejemplo: Cambio de mayúsculas y minúsculas

Descripción detallada:
Este ejemplo muestra cómo convertir una cadena a mayúsculas y minúsculas usando los métodos upper() y lower() en Python.
"""

if __name__ == "__main__":
    palabra = "Python"  # Cadena original
    # Mostramos la cadena en mayúsculas
    print(palabra.upper())
    # Mostramos la cadena en minúsculas
    print(palabra.lower())

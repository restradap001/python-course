"""
Ejemplos: Operaciones aritméticas básicas en Python

Descripción detallada:
Este archivo contiene ejemplos documentados de operaciones aritméticas en Python: suma, resta, multiplicación, división, división entera, módulo y exponenciación. Cada ejemplo muestra cómo realizar la operación y cómo mostrar el resultado por pantalla.
"""

if __name__ == "__main__":
    # Suma
    resultado = 5 + 3
    print(f"5 + 3 = {resultado}")

    # Resta
    resultado = 10 - 2
    print(f"10 - 2 = {resultado}")

    # Multiplicación
    resultado = 4 * 7
    print(f"4 * 7 = {resultado}")

    # División
    resultado = 20 / 4
    print(f"20 / 4 = {resultado}")

    # División entera
    resultado = 20 // 3
    print(f"20 // 3 = {resultado}")

    # Módulo
    resultado = 10 % 3
    print(f"10 % 3 = {resultado}")

    # Exponenciación
    resultado = 2 ** 3
    print(f"2 ** 3 = {resultado}")

"""
Ejemplo: Multiplicación y división

Descripción detallada:
Este ejemplo muestra cómo realizar operaciones de multiplicación y división en Python. Se definen dos variables, se calcula el producto y el cociente, y se muestran los resultados por pantalla.
"""

if __name__ == "__main__":
    x = 8  # Primer número
    y = 4  # Segundo número
    multiplicacion = x * y  # Multiplicación
    division = x / y  # División
    print(f"Multiplicación: {multiplicacion}")
    print(f"División: {division}")

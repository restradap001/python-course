"""
Ejemplo: Suma y resta de números

Descripción detallada:
Este ejemplo muestra cómo realizar operaciones básicas de suma y resta en Python. Se definen dos variables numéricas, se calcula la suma y la resta, y se muestran los resultados por pantalla.
"""

if __name__ == "__main__":
    a = 5  # Primer número
    b = 2  # Segundo número
    suma = a + b  # Suma de a y b
    resta = a - b  # Resta de a y b
    print(f"Suma: {suma}")
    print(f"Resta: {resta}")

"""
Ejemplo: Operación módulo

Descripción detallada:
Este ejemplo muestra cómo utilizar el operador módulo (%) en Python para obtener el residuo de una división. Se calcula el residuo de 15 dividido entre 4 y se muestra el resultado.
"""

if __name__ == "__main__":
    resultado = 15 % 4  # Residuo de 15 dividido entre 4
    print(f"15 % 4 = {resultado}")

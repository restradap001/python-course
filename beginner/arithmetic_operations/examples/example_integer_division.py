"""
Ejemplo: División entera

Descripción detallada:
Este ejemplo muestra cómo realizar una división entera en Python usando el operador //. Se calcula el cociente entero de 17 dividido entre 5 y se muestra el resultado.
"""

if __name__ == "__main__":
    resultado = 17 // 5  # División entera
    print(f"17 // 5 = {resultado}")

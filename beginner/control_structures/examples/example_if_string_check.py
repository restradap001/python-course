"""
Ejemplo: If para verificar una cadena

Descripción detallada:
Este ejemplo muestra cómo usar una sentencia if para comprobar si una cadena de texto no está vacía.
"""

if __name__ == "__main__":
    text = "hola"  # Cadena a verificar
    if text != "":
        # Si la cadena no está vacía
        print('La cadena no está vacía')

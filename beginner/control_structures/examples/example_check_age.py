"""
Ejemplo: Verificación de mayoría de edad

Descripción detallada:
Este ejemplo muestra cómo usar una estructura if-else para determinar si una persona es mayor de edad.
"""

if __name__ == "__main__":
    edad = 17
    if edad >= 18:
        print("Eres mayor de edad.")
    else:
        print("Eres menor de edad.")

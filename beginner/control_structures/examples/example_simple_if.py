"""
Ejemplo: Sentencia if simple

Descripción detallada:
Este ejemplo muestra cómo usar una sentencia if para comprobar si un número es mayor que 5. Si la condición se cumple, se imprime un mensaje por pantalla.
"""

if __name__ == "__main__":
    x = 10  # Número a evaluar
    if x > 5:
        # Si x es mayor que 5
        print('x es mayor que 5')

"""
Ejemplo: Tipo de dato NoneType

Descripción detallada:
Este ejemplo muestra cómo utilizar el valor especial None en Python. Se asigna None a la variable nothing y se imprime su valor y su tipo.
"""

if __name__ == "__main__":
    nothing = None  # Variable con valor None
    # Mostramos el valor y el tipo de la variable
    print(f"Nada: {nothing} (tipo: {type(nothing)})")

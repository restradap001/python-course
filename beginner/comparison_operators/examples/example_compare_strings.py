"""
Ejemplo: Comparación de cadenas

Descripción:
Compara dos cadenas de texto usando operadores de comparación.

Funciones útiles:
- ==
- !=
- print()
"""

if __name__ == "__main__":
    palabra1 = "hola"
    palabra2 = "adios"
    print(palabra1 == palabra2)  # False
    print(palabra1 != palabra2)  # True

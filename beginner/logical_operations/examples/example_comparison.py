"""
Ejemplo: Operadores de comparación

Descripción detallada:
Este ejemplo muestra cómo usar operadores de comparación en Python para comparar valores numéricos y obtener resultados booleanos.
"""

if __name__ == "__main__":
    a = 7  # Primer número
    b = 5  # Segundo número
    print(f"a > b: {a > b}")  # Mayor que
    print(f"a == b: {a == b}")  # Igualdad
    print(f"a != b: {a != b}")  # Diferente

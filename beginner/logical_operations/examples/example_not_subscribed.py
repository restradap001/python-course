"""
Ejemplo: Verificación de suscripción

Descripción detallada:
Este ejemplo muestra cómo usar el operador not para verificar si un usuario no está suscrito a un boletín.
"""

if __name__ == "__main__":
    suscrito = False
    if not suscrito:
        print("¿Deseas suscribirte al boletín?")
    else:
        print("Gracias por estar suscrito.")

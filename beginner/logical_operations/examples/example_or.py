"""
Ejemplo: Operador lógico OR

Descripción detallada:
Este ejemplo muestra cómo usar el operador lógico OR en Python. Se evalúa la disyunción de dos valores booleanos y se imprime el resultado.
"""

if __name__ == "__main__":
    x = False  # Primer valor booleano
    y = True   # Segundo valor booleano
    resultado = x or y  # OR lógico
    print(f"False or True: {resultado}")

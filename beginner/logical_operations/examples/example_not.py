"""
Ejemplo: Operador lógico NOT

Descripción detallada:
Este ejemplo muestra cómo usar el operador lógico NOT en Python para invertir el valor de una variable booleana.
"""

if __name__ == "__main__":
    flag = True  # Valor booleano
    resultado = not flag  # Negación lógica
    print(f"Not True: {resultado}")

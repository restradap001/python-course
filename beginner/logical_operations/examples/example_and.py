"""
Ejemplo: Operador lógico AND

Descripción detallada:
Este ejemplo muestra cómo usar el operador lógico AND en Python. Se evalúa la conjunción de dos valores booleanos y se imprime el resultado.
"""

if __name__ == "__main__":
    a = True  # Primer valor booleano
    b = False  # Segundo valor booleano
    resultado = a and b  # AND lógico
    print(f"True and False: {resultado}")

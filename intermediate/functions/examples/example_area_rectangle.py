"""
Ejemplo: Función para calcular el área de un rectángulo

Descripción detallada:
Este ejemplo muestra cómo definir una función que recibe la base y la altura de un rectángulo y devuelve su área.
"""

if __name__ == "__main__":
    def area_rectangulo(base, altura):
        return base * altura
    print(f"Área: {area_rectangulo(4, 5)}")

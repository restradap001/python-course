"""
Ejemplo: Función con parámetros

Descripción detallada:
Este ejemplo muestra cómo definir una función que recibe parámetros en Python. La función greet recibe un nombre y muestra un saludo personalizado.
"""

if __name__ == "__main__":
    def greet(name):
        # Mostramos un saludo personalizado
        print(f"¡Hola, {name}!")
    greet("Alice")  # Llamamos a la función con un argumento

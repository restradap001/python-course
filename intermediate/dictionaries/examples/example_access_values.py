"""
Ejemplo: Acceso a valores de un diccionario

Descripción detallada:
Este ejemplo muestra cómo acceder a los valores de un diccionario en Python usando las claves. Se imprime la marca y el año de un auto almacenado en el diccionario.
"""

if __name__ == "__main__":
    car = {'brand': 'Toyota', 'model': 'Corolla', 'year': 2020}  # Diccionario de ejemplo
    # Accedemos e imprimimos valores usando las claves
    print(car['brand'])
    print(car['year'])

"""
Ejemplo: Agregar un nuevo par clave-valor a un diccionario

Descripción detallada:
Este ejemplo muestra cómo agregar una nueva clave y su valor a un diccionario existente en Python.
"""

if __name__ == "__main__":
    car = {'brand': 'Toyota', 'model': 'Corolla', 'year': 2020}  # Diccionario original
    car['color'] = 'red'  # Agregamos una nueva clave 'color'
    print(car)  # Mostramos el diccionario actualizado

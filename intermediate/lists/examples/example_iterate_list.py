"""
Ejemplo: Recorrer una lista

Descripción detallada:
Este ejemplo muestra cómo recorrer los elementos de una lista utilizando un bucle for. Cada fruta de la lista se imprime en una línea diferente, mostrando cómo acceder y procesar cada elemento secuencialmente.
"""

if __name__ == "__main__":
    # Creamos una lista de frutas
    frutas = ['apple', 'banana', 'cherry']
    # Recorremos la lista e imprimimos cada fruta
    for fruta in frutas:
        print(fruta)

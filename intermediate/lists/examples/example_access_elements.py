"""
Ejemplo: Acceder a elementos de una lista

Descripción detallada:
Este ejemplo muestra cómo acceder a elementos individuales de una lista utilizando su índice. El código imprime el primer y segundo elemento de la lista, demostrando la indexación basada en cero en Python.
"""

if __name__ == "__main__":
    # Creamos una lista de frutas
    frutas = ['apple', 'banana', 'cherry']
    # Imprimimos el primer elemento (índice 0)
    print(frutas[0])
    # Imprimimos el segundo elemento (índice 1)
    print(frutas[1])

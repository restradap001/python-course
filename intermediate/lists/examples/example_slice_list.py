"""
Ejemplo: Rebanado (slicing) de una lista

Descripción detallada:
Este ejemplo muestra cómo utilizar el rebanado (slicing) para acceder a un subconjunto de elementos de una lista en Python. El código crea una lista de frutas e imprime una porción que contiene el segundo y tercer elemento.
"""

if __name__ == "__main__":
    # Creamos una lista de frutas
    frutas = ['apple', 'banana', 'cherry', 'orange']
    # Imprimimos los elementos en las posiciones 1 y 2 (del segundo al tercero)
    print(frutas[1:3])

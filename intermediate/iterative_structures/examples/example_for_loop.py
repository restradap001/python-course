"""
Ejemplo: Bucle for del 1 al 5

Descripción detallada:
Este ejemplo muestra cómo utilizar un bucle for en Python para iterar sobre un rango de números. El código imprime los números del 1 al 5, uno por línea.
"""

if __name__ == "__main__":
    # Usamos range para generar los números del 1 al 5
    for i in range(1, 6):
        print(i)  # Imprime el valor actual de i

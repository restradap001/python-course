"""
Ejemplo: Recorrer una lista con un bucle for

Descripción detallada:
Este ejemplo muestra cómo recorrer los elementos de una lista utilizando un bucle for en Python. Cada nombre de la lista se imprime en una línea diferente.
"""

if __name__ == "__main__":
    # Definimos una lista de nombres
    nombres = ['Alice', 'Bob', 'Charlie']
    # Recorremos la lista e imprimimos cada nombre
    for nombre in nombres:
        print(nombre)

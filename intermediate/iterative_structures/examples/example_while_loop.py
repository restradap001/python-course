"""
Ejemplo: Bucle while

Descripción detallada:
Este ejemplo muestra cómo utilizar un bucle while en Python para repetir una acción mientras se cumpla una condición. El código imprime los números del 1 al 3, incrementando la variable en cada iteración.
"""

if __name__ == "__main__":
    # Inicializamos la variable n en 1
    n = 1
    # El bucle se ejecuta mientras n sea menor o igual a 3
    while n <= 3:
        print(n)  # Imprime el valor actual de n
        n += 1    # Incrementa n en 1

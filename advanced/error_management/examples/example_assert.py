"""
Ejemplo: Uso de assert para validación

Descripción detallada:
Este ejemplo muestra cómo usar la instrucción assert para validar condiciones y lanzar una excepción si la condición no se cumple.
"""

if __name__ == "__main__":
    numero = 5
    assert numero > 0, "El número debe ser positivo."
    print("El número es positivo.")
